// pnpm auth:generate — regenerates src/schema/better-auth.ts with the Better Auth CLI, then moves
// the tables into the `better_auth` Postgres schema (one schema per module; `auth` is taken by
// Supabase). The move is the only change and is made here, so the file is never edited by hand.
// Afterwards run `pnpm db:generate better-auth` for the migration.
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const db = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(db, 'src', 'schema', 'better-auth.ts')
const work = mkdtempSync(join(tmpdir(), 'better-auth-'))
const raw = join(work, 'schema.ts')

function run(command, args) {
  const result = spawnSync(command, args, { cwd: db, stdio: 'inherit' })
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed`)
}

try {
  run('pnpm', [
    'exec',
    'auth',
    'generate',
    '--config',
    'better-auth/auth.config.ts',
    '--output',
    raw,
    '--yes',
  ])
  let source = readFileSync(raw, 'utf8')
  if (!/\bpgTable,/.test(source)) throw new Error('Unexpected CLI output: no pgTable import')
  source = source
    .replace(/\bpgTable,/, 'pgSchema,')
    .replace(
      /(} from "drizzle-orm\/pg-core";\n)/,
      `$1\nexport const betterAuth = pgSchema("better_auth");\n`,
    )
    .replaceAll('pgTable(', 'betterAuth.table(')
  const header = [
    '// Generated by `pnpm auth:generate` (Better Auth CLI, then moved into the `better_auth` schema).',
    '// Never edit by hand: change better-auth/auth.config.ts and regenerate. Owner: the auth module.',
    '',
  ].join('\n')
  writeFileSync(target, header + source)
  run('pnpm', ['exec', 'biome', 'check', '--write', target])
  console.log(`wrote ${target}`)
} finally {
  rmSync(work, { recursive: true, force: true })
}
