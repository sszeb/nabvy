// pnpm new:module <name> [--depends-on=core,switches]
// Scaffolds an atomic module (docs/decisions.md, "Atomic modules") in the merged shape
// services/usage-ledger uses, in exactly the files that module owns (docs/design/modules/_rules.md,
// rule 2), so parallel module branches never edit a shared file:
//   services/<name>/                          the module package (CLAUDE.md, _rules.md rule 2)
//   packages/contracts/src/modules/<name>.ts  its contracts and event registry
//   packages/config/src/modules/<name>.ts     its thresholds (_rules.md rule 14)
//   packages/db/src/schema/<name>.ts          its Drizzle tables, in its own Postgres schema
//   packages/db/migrations/<name>/            its migrations home: module.json + drizzle.config.ts
//   packages/db/tests/<name>.test.sql         its pnpm db:dry-run probe
// Then: pnpm install, define tables, pnpm db:generate <name> (packages/db/README.md).
//
// Every generated file it can carry a comment in opens with one line, "generated by
// scripts/new-module.mjs; edit freely", so a build session knows nothing here is sacred.
