const pascal = (name) =>
  name
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')

export function validateName(name) {
  if (!name || !MODULE_NAME.test(name)) {
    throw new Error(`Module name "${name ?? ''}" must be kebab case, e.g. copy-advert-spam`)
  }
  const schema = name.replaceAll('-', '_')
  if (
    RESERVED_NAMES.includes(name) ||
    RESERVED_SCHEMAS.includes(schema) ||
    schema.startsWith('pg_')
  ) {
    throw new Error(`Module name "${name}" is reserved`)
  }
  return schema
}

/** Parses `<name> [--depends-on=a,b]` from argv (after the node and script path). */
export function parseArgs(argv) {
  const [name, ...rest] = argv
  let dependsOn
  for (const arg of rest) {
    const match = /^--depends-on=(.*)$/.exec(arg)
    if (match) {
      dependsOn = match[1]
        .split(',')
        .map((part) => part.trim())
        .filter(Boolean)
    }
  }
  return { name, dependsOn }
}

/**
 * The workspace dependencies a generated module's package.json carries: exactly what
 * services/usage-ledger/package.json uses (the reference shape task 0.13 was told to match), so
 * the two never drift apart by hand.
 */
function referenceDependencies(root) {
  const pkg = JSON.parse(readFileSync(join(root, 'services/usage-ledger/package.json'), 'utf8'))
  if (!pkg.dependencies?.zod)
    throw new Error('services/usage-ledger/package.json has no zod dependency')
  return { dependencies: pkg.dependencies, devDependencies: pkg.devDependencies ?? {} }
}

