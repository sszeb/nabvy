#!/usr/bin/env node
// Split the module catalogue draft into one card per module, so a build
// session reads only its own card. Also writes index.json (job, group,
// round, dependencies, scope) for the catalogue page.
// Usage: node scripts/split-module-cards.mjs [draft] [outDir]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const draft = process.argv[2] ?? "docs/design/drafts/modules.md";
const outDir = process.argv[3] ?? "docs/design/modules";
const lines = readFileSync(draft, "utf8").split("\n");

const at = (re) => lines.findIndex((l) => re.test(l));
const cardsStart = at(/^## Module cards/);
const graphStart = at(/^## Dependency graph/);
const bpStart = at(/^## From the build pack/);

// Catalogue table: one job and priority per module.
const table = {};
for (const l of lines.slice(at(/^## Catalogue/), cardsStart)) {
  const m = l.match(/^\| `([a-z0-9-]+)` \| ([^|]+) \|.*\| ([^|]+) \|$/);
  if (m) table[m[1]] = { job: m[2].trim(), priority: m[3].trim() };
}

// Dependency rounds.
const round = {};
for (const l of lines.slice(graphStart, bpStart)) {
  const m = l.match(/^\| (\d+) \| (.+) \|$/);
  if (m) for (const [, n] of m[2].matchAll(/`([a-z0-9-]+)`/g)) round[n] = Number(m[1]);
}

// Scope from the "Not in the MVP" table.
const scope = {};
for (const l of lines.slice(at(/^## Catalogue/), cardsStart)) {
  const m = l.match(/^\| (After MVP|Later|Parked)[^|]* \| (.+) \|$/);
  if (m) for (const [, n] of m[2].matchAll(/`([a-z0-9-]+)`/g)) scope[n] = m[1];
}

mkdirSync(outDir, { recursive: true });
const index = [];
let group = "";
let card = null;
const flush = () => {
  if (!card) return;
  const body = card.lines.join("\n").trimEnd();
  const header = `<!-- Generated by scripts/split-module-cards.mjs from ${draft}; edit the draft, not this file. Shared rules: _rules.md -->\n\n**Group:** ${card.group}\n\n`;
  writeFileSync(join(outDir, `${card.name}.md`), `${header}${body}\n`);
  const dep = body.match(/^- \*\*Depends on:\*\* (.*)$/m)?.[1] ?? "";
  const deps = [...dep.matchAll(/`([a-z0-9-]+)`( \(soft\))?/g)];
  index.push({
    name: card.name,
    group: card.group,
    job: table[card.name]?.job ?? "",
    priority: table[card.name]?.priority ?? "",
    round: round[card.name] ?? null,
    scope: scope[card.name] ?? "MVP",
    dependsOn: deps.filter((d) => !d[2]).map((d) => d[1]),
    softDependsOn: deps.filter((d) => d[2]).map((d) => d[1]),
  });
  card = null;
};
for (const l of lines.slice(cardsStart + 1, graphStart)) {
  const g = l.match(/^\*\*([A-Z][^*]+)\*\*$/);
  const h = l.match(/^### `([a-z0-9-]+)`/);
  if (g) {
    flush();
    group = g[1];
  } else if (h) {
    flush();
    card = { name: h[1], group, lines: [l] };
  } else if (card) card.lines.push(l);
}
flush();

writeFileSync(
  join(outDir, "_rules.md"),
  `<!-- Generated by scripts/split-module-cards.mjs from ${draft}. -->\n\n${lines
    .slice(0, at(/^## Catalogue/))
    .join("\n")
    .trimEnd()}\n`,
);
writeFileSync(join(outDir, "index.json"), `${JSON.stringify(index, null, 2)}\n`);
console.log(`${index.length} cards -> ${outDir}`);
